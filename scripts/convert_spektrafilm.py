#!/usr/bin/env python3
"""Convert spektrafilm profile JSON (CC BY-SA 4.0, Andrea Volpato) into Emulsion 98's measured-data Swift file.

Usage: python3 -I scripts/convert_spektrafilm.py Data/spektrafilm/profiles Sources/FilmEngine/MeasuredData.swift

The output is a derivative of the profiles and therefore stays CC BY-SA 4.0 (see Data/spektrafilm).
Changes made: resampled to 380–780 nm in 5 nm steps; sensitivity converted from log10 to linear;
missing spectral samples held at the nearest measured value (negative masking values kept); characteristic and sublayer curves resampled to 141 points.
"""
import json, os, sys

WL = list(range(380, 781, 5))
LOGE = [-3.0 + 0.05 * i for i in range(141)]   # -3 … +4


def interp(xs, ys, x):
    pts = [(a, b) for a, b in zip(xs, ys) if b is not None]
    if not pts:
        return 0.0
    if x <= pts[0][0]:
        return pts[0][1]
    if x >= pts[-1][0]:
        return pts[-1][1]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= x <= x1:
            t = (x - x0) / (x1 - x0) if x1 > x0 else 0
            return y0 + (y1 - y0) * t
    return pts[-1][1]


def col(rows, k):
    return [r[k] if r is not None else None for r in rows]


def fmt(vals):
    return "[" + ", ".join(f"{v:.5g}" for v in vals) + "]"


def main(src, dst):
    out = []
    for f in sorted(os.listdir(src)):
        if not f.endswith(".json"):
            continue
        d = json.load(open(os.path.join(src, f)))
        info, data = d["info"], d["data"]
        wl = data["wavelengths"]
        sens = []
        for k in range(3):
            ls = col(data["log_sensitivity"], k)
            sens.append([10 ** interp(wl, ls, w) for w in WL])
        dyes = []
        for k in range(3):
            cd = col(data["channel_density"], k)
            # Keep negative values: masking couplers are encoded as negative absorption.
            # Outside the measured band hold the edge value (dye tails do not vanish abruptly).
            dyes.append([interp(wl, cd, w) for w in WL])
        base = [max(interp(wl, data["base_density"], w), 0) for w in WL]
        curves = []
        for k in range(3):
            dc = col(data["density_curves"], k)
            curves.append([interp(data["log_exposure"], dc, x) for x in LOGE])
        # Sublayer (fast / medium / slow emulsion) curves: data["density_curves_layers"][i][sublayer][channel].
        layers = []
        L = data.get("density_curves_layers")
        for k in range(3):
            per = []
            for sl in range(3):
                col_v = [row[sl][k] if row is not None and row[sl] is not None else None for row in L]
                per.append(fmt([interp(data["log_exposure"], col_v, x) for x in LOGE]))
            layers.append("[" + ", ".join(per) + "]")
        out.append(f'''        "{info["stock"]}": MeasuredProfile(
            id: "{info["stock"]}", name: "{info["name"]}", type: "{info["type"]}", support: "{info["support"]}",
            referenceIlluminant: "{info.get("reference_illuminant", "")}",
            sensitivity: [{fmt(sens[0])},
                          {fmt(sens[1])},
                          {fmt(sens[2])}],
            dyes: [{fmt(dyes[0])},
                   {fmt(dyes[1])},
                   {fmt(dyes[2])}],
            base: {fmt(base)},
            curves: [{fmt(curves[0])},
                     {fmt(curves[1])},
                     {fmt(curves[2])}],
            layerCurves: [{layers[0]},
                          {layers[1]},
                          {layers[2]}],
            antihalation: "{info.get("antihalation", "")}"),''')
    header = '''// GENERATED by scripts/convert_spektrafilm.py — do not edit.
//
// Measured film & paper data derived from spektrafilm profiles by Andrea Volpato,
// https://github.com/andreavolpato/spektrafilm — licensed CC BY-SA 4.0
// (see Data/spektrafilm/SPEKTRAFILM_LICENSE.txt). Modified by the Emulsion 98 project:
// resampled to 380–780 nm / 5 nm, log sensitivity converted to linear, gaps filled,
// characteristic curves resampled (see Data/spektrafilm/CHANGELOG.txt).
// This file, as a derivative of the profiles, is itself licensed CC BY-SA 4.0.
// Original data: Kodak and Fujifilm data sheets and scientific publications.

struct MeasuredProfile {
    let id: String, name: String, type: String, support: String, referenceIlluminant: String
    /// Linear spectral sensitivity of the R, G, B layers, 380…780 nm step 5.
    let sensitivity: [[Float]]
    /// Spectral density of the C, M, Y dyes.
    let dyes: [[Float]]
    /// Spectral density of the base (orange mask for negatives).
    let base: [Float]
    /// Density (over base) of the R, G, B layers vs log exposure −3…+4 step 0.05.
    let curves: [[Float]]
    /// Per channel, the density of its three sub-emulsions (fast, medium, slow) on the same axis.
    let layerCurves: [[[Float]]]
    /// Datasheet antihalation rating ("strong" / "weak").
    let antihalation: String
}

enum MeasuredData {
    static let logExposureStart: Float = -3
    static let logExposureStep: Float = 0.05
    static let profiles: [String: MeasuredProfile] = [
'''
    with open(dst, "w") as fh:
        fh.write(header + "\n".join(out) + "\n    ]\n}\n")
    print(f"wrote {len(out)} profiles to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
