#!/usr/bin/env python3
"""Builds Sources/FilmEngine/SkinData.swift from the NIST human skin reflectance data set.

Source: "Reference Data Set of Human Skin Reflectance", National Institute of Standards and Technology —
C. C. Cooksey, D. W. Allen, B. K. Tsai, J. Res. NIST 122, 26 (2017), doi:10.6028/jres.122.026.
File: https://opendata.nist.gov/1832_Data_JResNIST_skinrefl v3.txt (100 subjects, 250–2500 nm).
NIST data is not subject to copyright in the United States (17 U.S.C. §105); NIST is acknowledged as the source.

Changes (derived statistics only; the raw spectra are not redistributed): the 100 per-subject average
spectra are resampled to 380–780 nm in 5 nm steps, normalised to unit luminance (CIE Y under D65), and
reduced to a mean shape plus 4 principal components with their standard deviations; the CIE xy
chromaticities of the subjects are summarised by their mean and covariance.

Usage: python3 -I scripts/convert_nist_skin.py <nist file> Sources/FilmEngine/SkinData.swift
"""
import math, sys

WL = list(range(380, 781, 5))


def lobe(l, m, s1, s2):
    t = (l - m) / (s1 if l < m else s2)
    return math.exp(-0.5 * t * t)


# Same analytic CIE 1931 fit and D65 as the engine (Spectral.swift).
XB = [1.056 * lobe(l, 599.8, 37.9, 31.0) + 0.362 * lobe(l, 442.0, 16.0, 26.7) - 0.065 * lobe(l, 501.1, 20.4, 26.2) for l in WL]
YB = [0.821 * lobe(l, 568.8, 46.9, 40.5) + 0.286 * lobe(l, 530.9, 16.3, 31.1) for l in WL]
ZB = [1.217 * lobe(l, 437.0, 11.8, 36.0) + 0.681 * lobe(l, 459.0, 26.0, 13.8) for l in WL]
D10 = [49.98, 54.65, 82.75, 91.49, 93.43, 86.68, 104.86, 117.01, 117.81, 114.86, 115.92, 108.81, 109.35, 107.80, 104.79, 107.69,
       104.41, 104.05, 100.00, 96.33, 95.79, 88.69, 90.01, 89.60, 87.70, 83.29, 83.70, 80.03, 80.21, 82.28, 78.28, 69.72, 71.61,
       74.35, 61.60, 69.89, 75.09, 63.59, 46.42, 66.81, 63.38]
D65 = []
for l in WL:
    x = (l - 380) / 10; i = min(int(x), 39); t = x - i
    D65.append(D10[i] * (1 - t) + D10[i + 1] * t)
WY = sum(d * y for d, y in zip(D65, YB))


def xyz(r):
    return [sum(r[i] * c[i] * D65[i] for i in range(len(WL))) / WY for c in (XB, YB, ZB)]


def interp(xs, ys, x):
    for (x0, y0), (x1, y1) in zip(zip(xs, ys), zip(xs[1:], ys[1:])):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return ys[0] if x < xs[0] else ys[-1]


def main(src, dst):
    rows = []
    header = None
    for line in open(src, encoding="latin-1"):
        cells = line.rstrip("\n").split(",")
        if cells and cells[0].startswith("Wavelength"):
            header = cells
        elif header and cells and cells[0].strip().replace(".", "").isdigit():
            rows.append(cells)
    avg_cols = [i for i, h in enumerate(header) if h.strip() == "Average"]
    wl = [float(r[0]) for r in rows]
    spectra = []
    for c in avg_cols:
        ys = [float(r[c]) for r in rows]
        spectra.append([interp(wl, ys, l) for l in WL])
    n, m = len(spectra), len(WL)
    shapes, xys = [], []
    for s in spectra:
        X, Y, Z = xyz(s)
        shapes.append([v / Y for v in s])
        xys.append((X / (X + Y + Z), Y / (X + Y + Z)))
    mean = [sum(s[i] for s in shapes) / n for i in range(m)]
    cent = [[s[i] - mean[i] for i in range(m)] for s in shapes]
    cov = [[sum(c[i] * c[j] for c in cent) / (n - 1) for j in range(m)] for i in range(m)]
    total = sum(cov[i][i] for i in range(m))
    pcs, sig = [], []
    for k in range(4):
        v = [1.0 / math.sqrt(m)] * m
        for _ in range(500):
            w = [sum(cov[i][j] * v[j] for j in range(m)) for i in range(m)]
            for p in pcs:
                d = sum(a * b for a, b in zip(w, p)); w = [a - d * b for a, b in zip(w, p)]
            nrm = math.sqrt(sum(a * a for a in w)); v = [a / nrm for a in w]
        lam = sum(v[i] * sum(cov[i][j] * v[j] for j in range(m)) for i in range(m))
        pcs.append(v); sig.append(math.sqrt(max(lam, 0)))
        print(f"PC{k+1}: {100 * lam / total:.2f}% of shape variance")
    mx = sum(p[0] for p in xys) / n; my = sum(p[1] for p in xys) / n
    cxx = sum((p[0] - mx) ** 2 for p in xys) / (n - 1); cyy = sum((p[1] - my) ** 2 for p in xys) / (n - 1)
    cxy = sum((p[0] - mx) * (p[1] - my) for p in xys) / (n - 1)
    f = lambda vals: "[" + ", ".join(f"{v:.6g}" for v in vals) + "]"
    out = f'''// GENERATED by scripts/convert_nist_skin.py — do not edit.
//
// Derived from the NIST "Reference Data Set of Human Skin Reflectance" (Cooksey, Allen & Tsai,
// J. Res. NIST 122, 26, 2017; doi:10.6028/jres.122.026) — 100 subjects. Source: National Institute of
// Standards and Technology. Changes: resampled to 380–780 nm / 5 nm, normalised to unit luminance,
// reduced to a mean shape, 4 principal components and chromaticity statistics.

enum SkinData {{
    /// Mean skin reflectance shape (unit CIE Y under D65), 380…780 nm step 5.
    static let mean: [Float] = {f(mean)}
    /// Principal components of the shape and their standard deviations across subjects.
    static let components: [[Float]] = [{", ".join(f(p) for p in pcs)}]
    static let sigma: [Float] = {f(sig)}
    /// CIE xy chromaticity of the subjects (D65): mean and covariance.
    static let xyMean: SIMD2<Float> = [{mx:.6f}, {my:.6f}]
    static let xyCov: [Float] = [{cxx:.6g}, {cxy:.6g}, {cyy:.6g}]
    static let subjects = {n}
}}
'''
    open(dst, "w").write(out)
    print(f"{n} subjects, xy mean {mx:.4f} {my:.4f}, sd x {math.sqrt(cxx):.4f} y {math.sqrt(cyy):.4f}; wrote {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
